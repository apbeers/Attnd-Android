package com.arcu.attnd.util.integrity

import android.content.Context
import com.google.android.play.core.integrity.IntegrityManagerFactory
import com.google.android.play.core.integrity.IntegrityTokenRequest
import com.google.android.play.core.integrity.IntegrityTokenResponse
import kotlinx.coroutines.tasks.await

class IntegrityManager(private val context: Context) {

    private val integrityManager = IntegrityManagerFactory.create(context)

    /**
     * Requests an integrity token from the Play Integrity API.
     * This token should be sent to your backend server to verify the app's integrity.
     * 
     * @param nonce A unique string generated by your server to prevent replay attacks.
     */
    suspend fun fetchIntegrityToken(nonce: String): Result<String> {
        return try {
            val request = IntegrityTokenRequest.builder()
                .setNonce(nonce)
                // You can add your Cloud Project Number if using specific Google Cloud features:
                // .setCloudProjectNumber(yourProjectNumber)
                .build()

            val response: IntegrityTokenResponse = integrityManager.requestIntegrityToken(request).await()
            Result.success(response.token())
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
